import assert from 'node:assert/strict';
import { nextOccurrence } from '../src/lib/eventOccurrence.ts';
import { changeTimerLink, normalizeTimerLink } from '../src/lib/timerLink.ts';
const now = new Date('2026-10-12T12:00:00');
const event = {id:'e', date:'2026-10-05', title:'Evento', startTime:'09:00', repeat:'weekly'};
assert.equal(nextOccurrence(event,now)?.date,'2026-10-19','weekly occurrence after today\'s elapsed time');
assert.equal(nextOccurrence({...event,exceptions:['2026-10-19']},now)?.date,'2026-10-26','skip exception beyond one week');
assert.equal(nextOccurrence({...event,repeat:'daily',exceptions:Array.from({length:10},(_,i)=>`2026-10-${String(13+i).padStart(2,'0')}`)},now)?.date,'2026-10-23','more than seven exceptions');
assert.equal(nextOccurrence({...event,repeatUntil:'2026-10-18'},now),null,'recurrence limit');
assert.equal(nextOccurrence({...event,occurrenceOverrides:{'2026-10-19':{date:'2026-10-14',startTime:'14:00'}}},now)?.date,'2026-10-14','moved occurrence');
assert.equal(nextOccurrence({...event,repeat:'custom_days',repeatDays:[2,4]},now)?.date,'2026-10-14','Monday-zero weekday mapping');
assert.equal(nextOccurrence({...event,date:'2026-10-12',allDay:true,repeat:'none'},now)?.date,'2026-10-12','all-day survives until end of day');
assert.equal(nextOccurrence({...event,date:'2026-10-12',repeat:'none'},now),null,'past timed event excluded from upcoming');
assert.equal(nextOccurrence({...event,date:'bad'},now),null,'invalid date');
assert.equal(nextOccurrence({...event,repeat:'daily',occurrenceOverrides:{'2026-10-13':{date:'2026-10-25'}}},now)?.date,'2026-10-14','moved-out occurrence not duplicated');
let link=normalizeTimerLink(null);
link=changeTimerLink(link,'task','t1');assert.equal(link.activeTaskId,'t1');
link=changeTimerLink(link,'task',null);assert.deepEqual(link,{activeTaskId:null,activePlannedSessionId:null});
link=changeTimerLink(link,'task','t1');assert.equal(link.activeTaskId,'t1','same task can relink');
link=changeTimerLink(link,'session','s1');assert.deepEqual(link,{activeTaskId:null,activePlannedSessionId:'s1'});
link=changeTimerLink(link,'session',null);assert.deepEqual(link,{activeTaskId:null,activePlannedSessionId:null});
link=changeTimerLink(link,'task','t2');assert.equal(link.activeTaskId,'t2','task after unlink session');
assert.deepEqual(normalizeTimerLink({activeTaskId:'t1',activePlannedSessionId:'s1'}),{activeTaskId:'t1',activePlannedSessionId:null});
console.log('17/17 regression assertions passed');
