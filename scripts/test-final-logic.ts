import assert from 'node:assert/strict';
import {clockAngles,timeAtDial,clockValue} from '../src/lib/analogClock.ts';
import {deadlineForClock} from '../src/lib/timerSchedule.ts';
import {reorderNoteSubset} from '../src/lib/noteOrder.ts';
import {linkedStudyTitle,normalizeTimerLink,changeTimerLink} from '../src/lib/timerLink.ts';
const now=new Date('2026-10-13T10:20:30');
assert.deepEqual(clockAngles(now),{hour:310,minute:120});
assert.equal(clockValue(timeAtDial(270,'minute',now,new Date('2026-10-13T10:40:00'))),'10:45');
assert.equal(clockValue(timeAtDial(0,'minute',now,new Date('2026-10-13T11:10:00'))),'11:00');
assert.equal(clockValue(timeAtDial(330,'hour',now,new Date('2026-10-13T10:45:00'))),'11:45');
assert.equal(timeAtDial(90,'minute',new Date('2026-10-13T23:45:00'),new Date('2026-10-14T00:20:00')).getDate(),14);
const bounded=timeAtDial(180,'hour',now,new Date('2026-10-13T11:45:00'));
assert.ok(bounded>now && bounded.getTime()-now.getTime()<=7200000);
assert.equal(deadlineForClock('00:15',new Date('2026-10-13T23:45:00')).seconds,1800);
assert.equal(deadlineForClock('00:15',new Date('2026-10-13T21:00:00')).deadline,null);
const notes=['a','b','c','d'].map((id,sortOrder)=>({id,sortOrder}));
assert.deepEqual(reorderNoteSubset(notes,['d','b']).map(n=>n.id),['a','d','c','b']);
assert.deepEqual(reorderNoteSubset(notes,['d','b','d','missing']).map(n=>n.sortOrder),[0,1,2,3]);
assert.equal(reorderNoteSubset(notes,[]),notes);
assert.equal(reorderNoteSubset(notes,['b']),notes);
const task={title:'Preparar proyecto',subtasks:[{id:'s',title:'  Revisar fuentes  '}]};
assert.equal(linkedStudyTitle(task,'s'),'Revisar fuentes | Preparar proyecto');
assert.equal(linkedStudyTitle(task,'missing'),'Preparar proyecto');
assert.equal(linkedStudyTitle(undefined,'s'),undefined);
assert.equal(normalizeTimerLink({activeTaskId:'t',activeSubtaskId:'s'}).activeSubtaskId,'s');
assert.equal(normalizeTimerLink({activeSubtaskId:'s'}).activeSubtaskId,undefined);
assert.equal(changeTimerLink({activeTaskId:'t',activeSubtaskId:'s',activePlannedSessionId:null},'session','p').activeSubtaskId,undefined);
console.log('PASS 18 final cases: analog dial, bounds, midnight, filtered reorder and subtask identity');
