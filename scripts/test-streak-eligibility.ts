import assert from 'node:assert/strict';
import { calculateStreak, getGoalForDay } from '../src/lib/studyStreak.ts';
import { taskLinkUnavailable, sessionLinkUnavailable, eventLinkUnavailable } from '../src/lib/linkEligibility.ts';
const now=new Date(2026,9,12,14,0);
const totals={'2026-10-09':3600,'2026-10-10':3600,'2026-10-11':3600,'2026-10-13':3600};
assert.equal(calculateStreak(totals,60,undefined,undefined,now),3);
assert.equal(calculateStreak({...totals,'2026-10-12':3600},60,undefined,undefined,now),4);
assert.equal(calculateStreak({'2026-10-10':3600},60,undefined,undefined,now),0);
assert.equal(calculateStreak(totals,0,undefined,undefined,now),0);
assert.equal(calculateStreak({'2026-10-11':1800},60,{'2026-10-12':90},30,now),1);
assert.equal(getGoalForDay('2026-10-11',90,{'2026-10-10':45},30),45);
assert.equal(calculateStreak({'2026-10-11':NaN},60,undefined,undefined,now),0);
assert.ok(taskLinkUnavailable(undefined,now));
assert.ok(taskLinkUnavailable({status:'completado'},now));
assert.ok(taskLinkUnavailable({status:'inicio',dueDate:'2026-10-11'},now));
assert.ok(taskLinkUnavailable({status:'inicio',dueDate:'2026-10-12T10:00'},now));
assert.equal(taskLinkUnavailable({status:'inicio',dueDate:'2026-10-12'},now),null);
assert.equal(taskLinkUnavailable({status:'inicio'},now),null);
const session={id:'s',date:'2026-10-12',durationMinutes:25,completed:false};
assert.equal(sessionLinkUnavailable(session,now),null);
assert.equal(sessionLinkUnavailable({...session,startTime:'13:50'},now),null);
assert.ok(sessionLinkUnavailable({...session,startTime:'10:00'},now));
assert.ok(sessionLinkUnavailable({...session,completed:true},now));
assert.ok(sessionLinkUnavailable({...session,date:'2026-10-10'},now));
assert.equal(sessionLinkUnavailable({...session,date:'2026-10-10',repeat:'daily'},now),null);
assert.ok(sessionLinkUnavailable({...session,date:'2026-10-10',repeat:'daily',repeatUntil:'2026-10-11'},now));
assert.ok(sessionLinkUnavailable({...session,date:'2026-10-12',exceptions:['2026-10-12']},now));
assert.ok(eventLinkUnavailable({date:'2026-10-11',allDay:true,endTime:'23:59'},now));
assert.equal(eventLinkUnavailable({date:'2026-10-12',allDay:true,endTime:'23:59'},now),null);
assert.ok(eventLinkUnavailable({date:'2026-10-12',allDay:false,endTime:'10:00'},now));
assert.equal(eventLinkUnavailable({date:'2026-10-12',allDay:false,endTime:'18:00'},now),null);
assert.ok(taskLinkUnavailable({status:'inicio',dueDate:'bad'},now));
console.log('26/26 local streak and link eligibility assertions passed');
